/**
 * Returns translated string for given key in active language, falling back to English
 */
export function getTranslation(key: TranslationKey, lang: string): string {
  const normalizedLang = lang.toLowerCase();
  
  if (TRANSLATIONS[normalizedLang] && TRANSLATIONS[normalizedLang][key]) {
    return TRANSLATIONS[normalizedLang][key]!;
  }

  // Check base language (e.g. 'zh' from 'zh-CN')
  const base = normalizedLang.split('-')[0];
  if (TRANSLATIONS[base] && TRANSLATIONS[base][key]) {
    return TRANSLATIONS[base][key]!;
  }

  // Fallback to English
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key]!;
  }

  return key;
}
